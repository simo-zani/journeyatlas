/** Codice del frasario da usare per una lingua base in un certo paese (variante regionale o base). */
export const phrasebookCodeFor = (base: string, countryCode: string): string =>
  REGIONAL_VARIANTS[base]?.variants.find((v) => v.countries.includes(countryCode))?.code ?? base;

