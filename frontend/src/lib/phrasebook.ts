/** Vero se la lingua del frasario copre un nome di lingua del dataset paesi (anche tramite alias). */
export const coversLanguageName = (lang: PhrasebookLanguage, languageName: string): boolean =>
  [lang.name, ...(lang.aliases ?? [])].some((n) => languageName === n || languageName.startsWith(`${n} `));

/** Lingue del frasario disponibili, a partire dai nomi inglesi di REST Countries. */
export const phrasebookLanguagesFor = (languageNames: string[]): { code: string; lang: PhrasebookLanguage }[] =>
  Object.entries(LANGUAGES)
    .filter(([, lang]) => !lang.variantOf && languageNames.some((n) => coversLanguageName(lang, n)))
    .map(([code, lang]) => ({ code, lang }));
